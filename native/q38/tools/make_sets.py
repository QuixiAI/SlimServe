EVAL_FILES = ["README.md", "vllm/model_executor/models/qwen3_next.py", "perf/perf.md", "docs/README.md",
              "vllm/config/model.py", "slimserve/fetch.py", "perf/optimization_status.md:500000",
              "csrc/quixicore/metal/README.md"]


def main():
    ap = argparse.ArgumentParser()
    here = os.path.dirname(os.path.abspath(__file__))
    ap.add_argument("--pack", required=True)
    ap.add_argument("--out-dir", required=True)
    ap.add_argument("--model", default="~/models/Qwen3.8-27B")
    ap.add_argument("--gen", type=int, default=512)
    ap.add_argument("--file-len", type=int, default=384)
    ap.add_argument("--repo", default=os.path.join(here, "..", "..", ".."))
    ap.add_argument("--lab", default=os.path.join(here, "..", "build", "q38_lab"))
    ap.add_argument("--metallib", default=os.path.join(here, "..", "build", "q38_kernels.metallib")
                    + ":" + os.path.join(here, "..", "build", "q38_native.metallib"))
    a = ap.parse_args()
    out = os.path.expanduser(a.out_dir)
    os.makedirs(out, exist_ok=True)
    tok = AutoTokenizer.from_pretrained(os.path.expanduser(a.model))

    def generate(prompts, tag):
        seqs, labels = [], []
        for i, prompt in enumerate(prompts):
            text = tok.apply_chat_template([{"role": "user", "content": prompt}],
                                           add_generation_prompt=True, tokenize=False)
            ids = tok.encode(text, add_special_tokens=False)
            tf, of = os.path.join(out, f"_{tag}{i}.tokens"), os.path.join(out, f"_{tag}{i}.out")
            open(tf, "w").write(" ".join(map(str, ids)))
            subprocess.run([a.lab, "--pack", os.path.expanduser(a.pack), "--metallib", a.metallib,
                            "--tokens", tf, "--gen", str(a.gen), "--sample", "--seed", str(1000 + i),
                            "--out-tokens", of], check=True, stdout=subprocess.DEVNULL)
            gen = [int(x) for x in open(of).read().split()]
            seqs.append(ids + gen)
            labels.append(f"gen{i}")
            os.remove(tf)
            os.remove(of)
            print(f"  {tag} {i + 1}/{len(prompts)}: {len(ids)} + {len(gen)} tokens", flush=True)
        return seqs, labels

    def files(specs):
        seqs, labels = [], []
        for spec in specs:
            path, _, skip = spec.partition(":")
            full = os.path.join(a.repo, path)
            if not os.path.exists(full):
                print(f"  missing {path}, skipped")
                continue
            text = open(full, errors="ignore").read()[int(skip or 0):][: a.file_len * 8]
            ids = tok.encode(text, add_special_tokens=False)[: a.file_len]
            if len(ids) >= 64:
                seqs.append(ids)
                labels.append(os.path.basename(path))
        return seqs, labels

    for name, prompts, fl in (("calib2", CALIB_PROMPTS, CALIB_FILES), ("eval2", EVAL_PROMPTS, EVAL_FILES)):
        gs, gl = generate(prompts, name)
        fs, fll = files(fl)
        json.dump({"sequences": gs + fs, "labels": gl + fll}, open(os.path.join(out, name + "_set.json"), "w"))
        print(f"{name}: {len(gs + fs)} sequences, {sum(map(len, gs + fs))} tokens")


if __name__ == "__main__":
    main()
