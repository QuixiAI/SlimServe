#!/usr/bin/env python3
"""Build the calibration and evaluation token sets for quantization work.

  make_sets.py --pack P --out-dir DIR [--gen 512]

Half of each set is the model's own chat output (prompt through the chat
template, thinking on, default sampling, generated by the native engine), so
the sets look like serving traffic; the other half is local prose, docs and
source code. Calibration and evaluation use disjoint prompts and disjoint
files. One GPU process at a time: this runs q38_lab sequentially.
"""
